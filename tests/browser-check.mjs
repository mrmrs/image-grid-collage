import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text());});
await page.goto(process.env.APP_URL || 'http://127.0.0.1:5173');
await page.getByText('8 images in the mix').waitFor();
await page.waitForFunction(()=>document.querySelector('canvas')?.width>300);
await page.getByText('Composing',{exact:true}).waitFor({state:'hidden'});
await page.screenshot({path:'/tmp/fieldwork-initial.png',fullPage:true});
console.log('Initial screenshot saved. Canvas:',await page.locator('canvas[aria-label="Generative composition preview"]').evaluate(c=>({width:c.width,height:c.height,hasPixels:c.getContext('2d').getImageData(100,100,1,1).data[3]===255})));
await page.getByRole('button',{name:'circle mask',exact:true}).click();
await page.getByRole('spinbutton',{name:'Columns',exact:true}).fill('7');
await page.getByRole('button',{name:'Save preset',exact:true}).click();
await page.getByLabel('Preset name',{exact:true}).fill('Browser test study');
await page.getByLabel('Version note').fill('First circular composition');
await page.getByRole('dialog').getByRole('button',{name:'Save preset',exact:true}).click();
await page.getByRole('button',{name:'Regenerate',exact:true}).click();
await page.getByRole('button',{name:'Save preset',exact:true}).click();
await page.getByRole('button',{name:'Save version 2',exact:true}).click();
await page.getByRole('button',{name:'presets',exact:true}).click();
await page.getByRole('button',{name:'Version 1 First circular composition'}).click();
await page.getByText('Saved locally',{exact:true}).waitFor();
await page.reload();
await page.getByText('8 images in the mix').waitFor();
await page.getByRole('button',{name:'presets',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Version 1 First circular composition'}).getAttribute('class'),'selected');
assert.equal(await page.locator('.preset-item[open] summary').textContent(),'Browser test study2 versions');
console.log('Version 1 restored and persisted across reload.');
await page.getByRole('button',{name:'print',exact:true}).click();
await page.getByRole('switch',{name:'Enable halftone'}).check();
await page.getByLabel('Pattern',{exact:true}).selectOption('diamonds');
await page.getByLabel('Width',{exact:true}).fill('2');
await page.getByLabel('Height',{exact:true}).fill('2');
await page.getByLabel('Resolution',{exact:true}).fill('150');
await page.waitForFunction(()=>document.querySelector('canvas')?.width>300);
await page.getByText('Composing',{exact:true}).waitFor({state:'hidden'});
await page.screenshot({path:'/tmp/fieldwork-print.png',fullPage:true});
await page.getByRole('button',{name:'Export',exact:true}).click();
const downloadPromise=page.waitForEvent('download',{timeout:60000});
await page.getByRole('button',{name:'ZIP Print package + editable layers',exact:false}).click();
const download=await downloadPromise;
await download.saveAs('/tmp/fieldwork-test.zip');
console.log('Package downloaded:',download.suggestedFilename());
console.log('UI errors:',errors);
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'/tmp/fieldwork-mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
console.log('Mobile layout has no horizontal overflow.');
await browser.close();
if(errors.length)process.exitCode=1;
